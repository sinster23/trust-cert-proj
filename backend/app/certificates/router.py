"""M5 certificate endpoints.

* ``POST /certificates``       issue + persist (requires M2 ``certificate:issue``).
* ``GET  /certificates/{id}``  retrieve an issued certificate (requires login).

Authentication comes from M1 and authorization from M2; nothing is
re-implemented here. The certificate ID and issue date are always generated by
the backend (``CertificateIssueRequest`` rejects client-supplied values).
"""

from __future__ import annotations

import logging
from typing import Annotated, Any

from fastapi import APIRouter, Depends, HTTPException, Path, Request, status

from ..auth.dependencies import DATABASE_MANAGER_STATE_ATTRS, get_current_user
from ..authorization.dependencies import require_permission
from ..authorization.permissions import Permission
from ..crypto import CryptoService
from ..crypto.exceptions import CryptoError
from ..database.connection import DatabaseManager
from ..database.exceptions import DatabaseError, DuplicateDataError
from ..database.repositories.certificate_repository import CertificateRepository
from .exceptions import (
    CertificateError,
    CertificateValidationError,
)
from .schemas import CertificateIssueRequest, IssuedCertificateResponse
from .service import CertificateService

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/certificates", tags=["certificates"])

CERTIFICATE_ID_PATTERN = r"^CERT-[0-9a-f]{32}$"


def _unavailable(detail: str) -> HTTPException:
    return HTTPException(status.HTTP_503_SERVICE_UNAVAILABLE, detail)


def get_crypto_service() -> CryptoService:
    try:
        return CryptoService()
    except CryptoError:
        logger.error("Signing service is not configured correctly")
        raise _unavailable("Signing service unavailable")


def get_certificate_repository(request: Request) -> CertificateRepository:
    """Build the M4 repository from the shared DatabaseManager on app.state."""
    for attr in DATABASE_MANAGER_STATE_ATTRS:
        manager = getattr(request.app.state, attr, None)
        if isinstance(manager, DatabaseManager):
            try:
                return CertificateRepository(manager.get_database())
            except DatabaseError:
                raise _unavailable("Certificate service unavailable")
    logger.error("DatabaseManager not found on app.state")
    raise _unavailable("Certificate service unavailable")


def get_certificate_service(
    crypto: Annotated[CryptoService, Depends(get_crypto_service)],
    repository: Annotated[CertificateRepository, Depends(get_certificate_repository)],
) -> CertificateService:
    return CertificateService(crypto, repository)


@router.post(
    "",
    status_code=status.HTTP_201_CREATED,
    response_model=IssuedCertificateResponse,
)
async def issue_certificate(
    # Authorization first, so unauthenticated/unauthorized callers never reach the service.
    issuer: Annotated[Any, Depends(require_permission(Permission.CERTIFICATE_ISSUE))],
    request: CertificateIssueRequest,
    service: Annotated[CertificateService, Depends(get_certificate_service)],
) -> IssuedCertificateResponse:
    try:
        signed = await service.issue_certificate(**request.model_dump())
    except CertificateValidationError as exc:
        raise HTTPException(422, str(exc))
    except DuplicateDataError:
        raise HTTPException(
            status.HTTP_409_CONFLICT, "Certificate ID conflict; please retry"
        )
    except CryptoError:
        logger.exception("Certificate signing failed")
        raise _unavailable("Signing service unavailable")
    except DatabaseError:
        logger.exception("Certificate persistence failed")
        raise _unavailable("Certificate service unavailable")
    return IssuedCertificateResponse.from_signed(signed)


@router.get("/{certificate_id}", response_model=IssuedCertificateResponse)
async def get_certificate(
    user: Annotated[Any, Depends(get_current_user)],
    certificate_id: Annotated[str, Path(pattern=CERTIFICATE_ID_PATTERN)],
    service: Annotated[CertificateService, Depends(get_certificate_service)],
) -> IssuedCertificateResponse:
    try:
        signed = await service.get_certificate(certificate_id)
    except CertificateError:
        logger.exception("Stored certificate could not be read")
        raise HTTPException(
            status.HTTP_500_INTERNAL_SERVER_ERROR, "Stored certificate could not be read"
        )
    except DatabaseError:
        logger.exception("Certificate retrieval failed")
        raise _unavailable("Certificate service unavailable")
    if signed is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Certificate not found")
    return IssuedCertificateResponse.from_signed(signed)